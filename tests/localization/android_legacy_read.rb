load File.join(ENV.fetch("KIF_QA_SUPPORT"),"scripts/multiplayer/test-bootstrap.rb")
check=KIFMultiplayerFeatureTest.method(:check)
folder=File.join(ENV.fetch("KIF_ANDROID_FILES"),"diagnostics/android15-fixtures")
original=File.join(folder,"android14-save.rxdata")
expected=File.open(File.join(folder,"expected.rxdata"),"rb") { |file| Marshal.load(file) }
check.call(expected["marker"]=="ANDROID14_QA_FIXTURE","fixture is generated by the published14 game code")
check.call(Digest::SHA256.hexdigest(File.binread(original))==expected["save_sha256"],"original14 save remains intact")
candidate=File.join(ENV.fetch("KIF_MULTIPLAYER_SAVE_DIR"),"legacy-load.rxdata")
File.binwrite(candidate,File.binread(original))
save=SaveData.read_from_file(candidate)
check.call(SaveData.valid?(save),"Android15 accepts the complete14 save schema")
# Recreate a clean boot: the shared diagnostic bootstrap initially marks defaults loaded.
SaveData.instance_variable_get(:@values).each(&:mark_as_unloaded)
SaveData.load_bootup_values(save)
Game.load(save)
check.call($Trainer.name==expected["trainer"] && $Trainer.money==expected["money"],"trainer name and money survive upgrade")
pokemon=$Trainer.party.first
check.call(pokemon.name==expected["nickname"] && pokemon.species.to_s==expected["species"] && pokemon.level==expected["level"],"nickname species and level survive upgrade")
check.call($Trainer.quests.map(&:name)==expected["quest_names"] && $Trainer.quests.map(&:completed)==expected["completed"],"all old quest names and completion flags survive")
check.call([$game_map.map_id,$game_player.x,$game_player.y]==[expected["map"],expected["x"],expected["y"]],"map and coordinates survive upgrade")
check.call(pbGet(VAR_TYPE_EXPERTS_BEATEN)==7,"old expert progress survives")
GameLanguage.load($PokemonSystem.language)
check.call($PokemonSystem.language==2 && _INTL("Options")=="设置","saved Chinese preference restores")
raw=Marshal.dump($Trainer.quests)
$Trainer.quests.each { |quest| [quest.name,quest.desc,quest.location,quest.npc].each { |value| check.call(pbQuestText(value).match?(/[\u3400-\u9fff]/),"old quest field is displayed in Chinese") } }
expert=$Trainer.quests.find { |quest| quest.name=="Type Experts" }
check.call(pbQuestText(expert.desc).include?("7/12"),"old expert count is displayed unchanged")
[0,2,1,2].each { |language| GameLanguage.load(language) }
check.call(Marshal.dump($Trainer.quests)==raw,"language switching leaves old stored fields unchanged")
$scene.createSpritesets
Graphics.update
Graphics.screenshot(File.join(ENV.fetch("KIF_MULTIPLAYER_SAVE_DIR"),"legacy-loaded-map-android.png"))
$scene.dispose
$scene=Object.new
load File.join(ENV.fetch("KIF_QA_SUPPORT"),"tests/localization/quest_dialogue_game.rb")
check.call(Game.save(expected["save_slot"]),"upgraded game can save again through the actual slot API")
File.binwrite(File.join(folder,"android15-save.rxdata"),File.binread(SaveData.get_full_path(expected["save_slot"])))
check.call(Digest::SHA256.hexdigest(File.binread(original))==expected["save_sha256"],"upgrade never rewrites the original fixture")
KIFMultiplayerFeatureTest.log("LEGACY14_TO15_PASS quests=#{$Trainer.quests.length} normal_player_saves=false")
exit!(0)
